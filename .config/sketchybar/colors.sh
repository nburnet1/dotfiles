#!/bin/bash

# Color Palette - Bulwer Dark Theme
# Based on James Bulwer Omarchy theme, adapted for dark mode
# Wallpaper: Landscape by the Shore with Road in Foreground

# Dark Bulwer Colors (inverted from light theme)
# Background: dark earthy brown instead of cream
# Foreground: warm cream/tan instead of dark brown
# Accents: warmer, brighter versions for dark mode visibility

# Bar - dark warm background
export BAR_COLOR=0xd01a1410          # Very dark brown, semi-transparent
export BRACKET_COLOR=0x30c4b8a0      # Warm tan, subtle

# Icons and Labels - warm cream foreground
export ICON_COLOR=0xffd4c8b0         # Warm cream
export LABEL_COLOR=0xffd4c8b0        # Warm cream
export SUBTLE_COLOR=0x60a09080       # Muted warm gray

# Accent - golden amber (from Bulwer earth tones)
export ACCENT_COLOR=0xffbc8400       # Bright gold/amber

# Status Indicators - Bulwer palette adapted for dark mode
export GREEN=0xff2e9ea9              # Coastal teal (bright_green)
export YELLOW=0xffbc8400             # Golden amber (bright_red in Bulwer)
export ORANGE=0xffa37926             # Warm orange/brown
export RED=0xff936100                # Earthy orange-brown
export BLUE=0xff2a8494               # Coastal blue (bright_magenta)

# Workspace Colors - MORE VISIBLE active state
export WORKSPACE_ACTIVE_BG=0xffbc8400   # Bright gold/amber - more visible!
export WORKSPACE_ACTIVE_FG=0xff1a1410   # Dark brown text on bright bg
export WORKSPACE_INACTIVE_BG=0x00000000 # Transparent
export WORKSPACE_INACTIVE_FG=0xffd4c8b0 # Warm cream
export WORKSPACE_EMPTY_FG=0x60a09080    # Muted warm gray
